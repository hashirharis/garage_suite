class Payment(models.Model):
    _inherit = 'account.payment'
    garage_payment = fields.Boolean(compute='_compute_garage_payment', search='_search_garage_payment', string='Garage Service Payment')

    @api.depends('reconciled_invoice_ids.garage_job_id', 'invoice_ids.garage_job_id')
    def _compute_garage_payment(self):
        for payment in self:
            payment.garage_payment = bool((payment.reconciled_invoice_ids | payment.invoice_ids).garage_job_id)

    def _search_garage_payment(self, operator, value):
        if operator in ('=', '!='):
            wanted = bool(value) if operator == '=' else not bool(value)
        elif operator in ('in', 'not in'):
            choices = set(bool(v) for v in value)
            if len(choices) != 1:
                all_records = (len(choices) == 2) == (operator == 'in')
                return [(1, '=', 1)] if all_records else [('id', '=', 0)]
            wanted = next(iter(choices))
            if operator == 'not in':
                wanted = not wanted
        else:
            raise NotImplementedError('Unsupported Garage payment search operator')
        # The native computed relation accepts invoice IDs, not a dotted `any`
        # domain. Keep both the invoice lookup and payment search under user ACLs.
        invoices = self.env['account.move'].search([('garage_job_id', '!=', False)])
        return [('reconciled_invoice_ids', 'in' if wanted else 'not in', invoices.ids)]
