from odoo import api, fields, models, Command, _
from odoo.exceptions import AccessError, ValidationError


class Job(models.Model):
    _inherit = 'garage.job.card'
    invoice_ids = fields.One2many('account.move', 'garage_job_id', groups='garage_core.group_garage_cashier,garage_core.group_garage_user')
    credit_release_reason = fields.Text(tracking=True, copy=False, groups='garage_core.group_garage_manager')
    credit_release_by = fields.Many2one('res.users', readonly=True, copy=False, groups='garage_core.group_garage_manager')
    credit_release_at = fields.Datetime(readonly=True, copy=False, groups='garage_core.group_garage_manager')

    service_revenue = fields.Monetary(compute='_compute_margin', store=True, groups='garage_core.group_garage_cashier,garage_core.group_garage_owner')
    service_cost = fields.Monetary(compute='_compute_margin', store=True, groups='garage_core.group_garage_manager,garage_core.group_garage_owner')
    service_margin = fields.Monetary(compute='_compute_margin', store=True, groups='garage_core.group_garage_manager,garage_core.group_garage_owner')

    @api.depends('invoice_ids.state', 'invoice_ids.amount_untaxed_signed', 'time_entry_ids.labour_cost', 'part_movement_ids.consumed_cost')
    def _compute_margin(self):
        for job in self:
            job.service_revenue = sum(job.invoice_ids.filtered(lambda i: i.state == 'posted').mapped('amount_untaxed_signed'))
            job.service_cost = sum(job.time_entry_ids.mapped('labour_cost')) + sum(job.part_movement_ids.mapped('consumed_cost'))
            job.service_margin = job.service_revenue - job.service_cost

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('credit_release_by') or vals.get('credit_release_at'):
                raise AccessError(_('Credit-release evidence is generated only by its manager action.'))
        return super().create(vals_list)

    def _check_release(self):
        for job in self:
            # This boolean gate exposes no private account documents to reception.
            invoices = self.env['account.move'].sudo().search([('garage_job_id', '=', job.id), ('move_type', '=', 'out_invoice'), ('state', '!=', 'cancel')])
            if not invoices or any(move.state != 'posted' for move in invoices):
                raise ValidationError(_('A posted service invoice is required before handover.'))
            if any(move.amount_residual > move.currency_id.rounding / 2 for move in invoices) and not (job.sudo().credit_release_by and job.sudo().credit_release_reason):
                raise ValidationError(_('Settle the service invoice or obtain a recorded manager credit release.'))

    def action_credit_release(self):
        self._require_role('manager')
        for job in self:
            if job.state != 'ready' or not (job.credit_release_reason or '').strip():
                raise ValidationError(_('Credit release requires a ready visit and a business reason.'))
            # Bypass only the protected audit-field input guard; normal ACLs remain.
            super(Job, job).write({'credit_release_by': self.env.user.id, 'credit_release_at': fields.Datetime.now()})

    def write(self, vals):
        if {'credit_release_by', 'credit_release_at'} & vals.keys():
            raise AccessError(_('Credit-release evidence is generated by the manager action.'))
        if 'credit_release_reason' in vals:
            self._require_role('manager')
            if self.filtered('credit_release_by'):
                raise ValidationError(_('The recorded credit release reason is immutable.'))
        return super().write(vals)

    def action_create_invoice(self):
        self.ensure_one()
        self._require_role('cashier')
        if self.state != 'ready':
            raise ValidationError(_('Final quality readiness is required before invoicing.'))
        self.env.cr.execute('SELECT id FROM garage_job_card WHERE id = %s FOR UPDATE', [self.id])
        invoice = self.env['account.move'].search([('garage_job_id', '=', self.id), ('move_type', '=', 'out_invoice'), ('state', '!=', 'cancel')], limit=1)
        if not invoice:
            order = self._approved_estimate()
            if not order:
                raise ValidationError(_('Only current approved work can be invoiced.'))
            order.check_access('read')
            lines = []
            for line in order.order_line.filtered(lambda l: not l.display_type):
                quantity = line.product_uom_qty
                if line.product_id.type == 'consu':
                    movements = self.part_movement_ids.filtered(lambda m: m.product_id == line.product_id and m.kind == 'consume')
                    used = sum(movements.mapped('quantity'))
                    quantity = line.product_id.uom_id._compute_quantity(used, line.product_uom_id)
                    siblings = order.order_line.filtered(lambda l: l.product_id == line.product_id and not l.display_type)
                    if len(siblings) != 1:
                        raise ValidationError(_('Use a single estimate line per parts product for unambiguous consumption billing.'))
                if quantity > line.product_uom_qty + 0.00001:
                    raise ValidationError(_('Billable consumption exceeds current approved scope.'))
                if quantity:
                    lines.append(Command.create(line._prepare_invoice_line(quantity=quantity)))
            if not lines:
                raise ValidationError(_('There are no completed billable lines.'))
            values = order._prepare_invoice()
            values.update(garage_job_id=self.id, garage_estimate_id=order.id, garage_billing_key=str(self.id), invoice_line_ids=lines)
            invoice = self.env['account.move'].create(values)
        return {'type': 'ir.actions.act_window', 'res_model': 'account.move', 'res_id': invoice.id, 'views': [(False, 'form')]}


class Move(models.Model):
    _inherit = 'account.move'
    garage_job_id = fields.Many2one('garage.job.card', check_company=True, copy=False, index=True, ondelete='restrict')
    garage_estimate_id = fields.Many2one('sale.order', check_company=True, copy=False, ondelete='restrict')
    garage_billing_key = fields.Char(copy=False, index=True)
    garage_correction_reason = fields.Text(copy=False, tracking=True)
    _garage_billing_unique = models.Constraint('UNIQUE(garage_billing_key)', 'This job already has a service invoice.')

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('garage_job_id'):
                job = self.env['garage.job.card'].browse(vals['garage_job_id'])
                job._require_role('cashier')
                if vals.get('move_type', 'entry') == 'out_invoice':
                    if job.state != 'ready':
                        raise ValidationError(_('Garage invoices require a ready job.'))
                    vals['garage_billing_key'] = str(job.id)
                elif vals.get('move_type') != 'out_refund':
                    raise ValidationError(_('Garage visits link only customer invoices and their credit notes.'))
                if vals.get('company_id', job.company_id.id) != job.company_id.id or vals.get('partner_id') != job.customer_id.id:
                    raise ValidationError(_('Invoice company and payer must match this service visit.'))
        return super().create(vals_list)

    def write(self, vals):
        garage = self.filtered('garage_job_id')
        if garage and {'garage_job_id', 'garage_estimate_id', 'garage_billing_key', 'partner_id', 'company_id'} & vals.keys():
            raise AccessError(_('Service invoice source references are protected.'))
        if garage and 'garage_correction_reason' in vals:
            garage.garage_job_id._require_role('manager')
        if garage and vals.get('state') == 'posted':
            garage._check_garage_posting()
        if garage and vals.get('state') in ('draft','cancel') and garage.filtered(lambda m: m.state == 'posted'):
            garage.garage_job_id._require_role('manager')
            if any(not m.garage_correction_reason or m.garage_job_id.state in ('delivered','closed') for m in garage):
                raise ValidationError(_('Retain delivered invoices. Otherwise record a manager correction reason before changing posting state.'))
        if garage and 'invoice_line_ids' in vals:
            raise ValidationError(_('Service billing lines are generated from approved scope and consumption. Correct scope before invoicing.'))
        return super().write(vals)

    def _validate_garage_scope(self):
        for move in self.filtered(lambda m: m.garage_job_id and m.move_type == 'out_invoice'):
            order = move.garage_job_id._approved_estimate()
            seen = self.env['sale.order.line']
            for line in move.invoice_line_ids.filtered(lambda l: l.display_type == 'product'):
                source = line.sale_line_ids
                if len(source) != 1 or source.order_id != order or source in seen:
                    raise ValidationError(_('Each service invoice line must reference one distinct approved estimate line.'))
                seen |= source
                quantity = source.product_uom_qty
                if source.product_id.type == 'consu':
                    consumed = sum(move.garage_job_id.part_movement_ids.filtered(lambda m: m.product_id == source.product_id and m.kind == 'consume').mapped('quantity'))
                    quantity = source.product_id.uom_id._compute_quantity(consumed, source.product_uom_id)
                if line.product_id != source.product_id or line.product_uom_id != source.product_uom_id or abs(line.quantity - quantity) > 0.00001 or abs(line.price_unit - source.price_unit) > 0.00001 or line.discount != source.discount or line.tax_ids != source.tax_ids:
                    raise ValidationError(_('Invoice quantities, prices, discounts and taxes must match approved work and actual consumption.'))
            expected = order.order_line.filtered(lambda l: not l.display_type and (l.product_id.type != 'consu' or move.garage_job_id.part_movement_ids.filtered(lambda m: m.product_id == l.product_id and m.kind == 'consume')))
            if set(seen.ids) != set(expected.ids):
                raise ValidationError(_('Include every eligible approved scope line exactly once.'))

    def _check_garage_posting(self):
        for move in self.filtered('garage_job_id'):
            move.garage_job_id._require_role('cashier')
            if move.move_type == 'out_refund':
                move.garage_job_id._require_role('manager')
                original = move.reversed_entry_id
                if not original or original.garage_job_id != move.garage_job_id or not move.garage_correction_reason or move.currency_id != original.currency_id:
                    raise ValidationError(_('Credit notes require the original service invoice, currency and a manager correction reason.'))
                other_credits = self.search([('reversed_entry_id', '=', original.id), ('state', '=', 'posted'), ('move_type', '=', 'out_refund'), ('id', '!=', move.id)])
                if sum(other_credits.mapped('amount_total')) + move.amount_total > original.amount_total + original.currency_id.rounding / 2:
                    raise ValidationError(_('Cumulative service credit notes cannot exceed the original invoice.'))
            if move.move_type == 'out_invoice' and (move.garage_job_id.state != 'ready' or move.garage_estimate_id != move.garage_job_id._approved_estimate() or move.currency_id != move.garage_estimate_id.currency_id):
                raise ValidationError(_('Recheck job readiness, currency and current approved scope before posting.'))
        self._validate_garage_scope()

    def action_post(self):
        self._check_garage_posting()
        return super().action_post()

    def _post(self, soft=True):
        self._check_garage_posting()
        return super()._post(soft=soft)

    def button_cancel(self):
        for move in self.filtered('garage_job_id'):
            move.garage_job_id._require_role('manager')
            if not move.garage_correction_reason:
                raise ValidationError(_('Record the invoice cancellation reason.'))
        result = super().button_cancel()
        for move in self.filtered('garage_job_id'):
            super(Move, move).write({'garage_billing_key': False})
        return result

    def _reverse_moves(self, default_values_list=None, cancel=False):
        defaults = default_values_list or [{} for move in self]
        for move, values in zip(self, defaults):
            if move.garage_job_id:
                move.garage_job_id._require_role('manager')
                if not move.garage_correction_reason:
                    raise ValidationError(_('Record the correction reason on the original invoice first.'))
                values.update(garage_job_id=move.garage_job_id.id, garage_estimate_id=move.garage_estimate_id.id, garage_correction_reason=move.garage_correction_reason, garage_billing_key=False)
        return super()._reverse_moves(defaults, cancel=cancel)


class MoveLine(models.Model):
    _inherit = 'account.move.line'
    garage_job_id = fields.Many2one(related='move_id.garage_job_id', store=True, index=True)
    garage_line_kind = fields.Selection([('labour', 'Labour'), ('parts', 'Parts'), ('package', 'Package')], compute='_compute_garage_revenue', store=True)
    garage_revenue = fields.Monetary(compute='_compute_garage_revenue', store=True, currency_field='company_currency_id')

    @api.depends('move_id.state', 'move_id.move_type', 'move_id.garage_job_id', 'product_id', 'balance')
    def _compute_garage_revenue(self):
        for line in self:
            line.garage_line_kind = 'parts' if line.product_id.type == 'consu' else 'package' if line.product_id == line.move_id.garage_job_id.package_id.product_id else 'labour'
            line.garage_revenue = -line.balance if line.move_id.garage_job_id and line.move_id.state == 'posted' and line.move_id.move_type in ('out_invoice','out_refund') and line.display_type == 'product' else 0

    def write(self, vals):
        protected = {'product_id', 'quantity', 'price_unit', 'discount', 'tax_ids', 'account_id', 'sale_line_ids', 'move_id', 'name'}
        if protected & vals.keys() and any(l.move_id.garage_job_id and l.display_type == 'product' for l in self):
            raise ValidationError(_('Garage invoice commercial lines come from approved service scope.'))
        return super().write(vals)

    def unlink(self):
        if any(l.move_id.garage_job_id and l.display_type == 'product' for l in self):
            raise ValidationError(_('Service invoice source lines are retained.'))
        return super().unlink()


class Order(models.Model):
    _inherit = 'sale.order'
    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('garage_job_id') and self.env['account.move'].sudo().search_count([('garage_job_id', '=', vals['garage_job_id']), ('move_type', '=', 'out_invoice'), ('state', '!=', 'cancel')]):
                raise ValidationError(_('Reconcile the existing invoice before revising billable scope.'))
        return super().create(vals_list)

    def _create_invoices(self, *args, **kwargs):
        if self.filtered('garage_job_id'):
            raise ValidationError(_('Generate service invoices from the ready job card to reconcile parts consumption.'))
        return super()._create_invoices(*args, **kwargs)


